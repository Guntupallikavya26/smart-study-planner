// Helper to calculate total & completed topics dynamically
export function calculateSubjectTopics(subject) {
  const total = subject.topics ? subject.topics.length : (subject.totalTopics || 0);
  const completed = subject.topics ? subject.topics.filter(t => t.completed).length : (subject.completedTopics || 0);
  const pending = total - completed;
  return { total, completed, pending };
}

